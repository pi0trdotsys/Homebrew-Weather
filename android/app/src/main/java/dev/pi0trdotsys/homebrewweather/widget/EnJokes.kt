/** The footer / brief-tail line for a tone and language, from the right pool. */
object Jokes {
    fun pick(
        tone: Tone,
        lang: Lang,
        kind: String,
        isNight: Boolean,
        seed: Int,
        temperature: Double = Double.NaN,
        dayOfWeek: Int? = null,
    ): String = when (tone) {
        Tone.CLEAN ->
            if (lang == Lang.EN) EnJokes.pickClean(kind, isNight, seed, temperature, dayOfWeek)
            else CleanJokes.pick(kind, isNight, seed, temperature, dayOfWeek)
        Tone.SIGMA, Tone.RUDE ->
            if (lang == Lang.EN) EnJokes.pickSigma(kind, isNight, seed, temperature, dayOfWeek)
            else SigmaJokes.pick(kind, isNight, seed, temperature, dayOfWeek)
    }
}
