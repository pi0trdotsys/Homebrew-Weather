// Generates src/lib/jokes.generated.ts and src/lib/wellbeing.generated.ts from
// the Kotlin pools, which are the source of truth (the widget footer has the
// hard 50-character limit and the tests that enforce it). Run after editing
// any of them:
//
//   bun scripts/gen-jokes.ts
//
// Reads CleanJokes.kt and SigmaJokes.kt (Polish) and EnJokes.kt (English) for
// the jokes, and WellbeingTips.kt (both languages) for the well-being tips.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const widgetDir = join(root, "android/app/src/main/java/dev/pi0trdotsys/homebrewweather/widget");

/** Parses `private val NAME: Map<String, List<String>> = mapOf( "kind" to listOf("…", …), … )`. */
function parsePools(file: string, name: string): Record<string, string[]> {
  // Normalised: a Windows checkout has CRLF, and the patterns below expect \n.
  const src = readFileSync(join(widgetDir, file), "utf8").replace(/\r\n/g, "\n");
  const start = src.indexOf(`private val ${name}: Map<String, List<String>> = mapOf(`);
  if (start < 0) throw new Error(`${name} not found in ${file}`);
  const pools: Record<string, string[]> = {};
  let current: string[] | null = null;
  for (const line of src.slice(start).split("\n").slice(1)) {
    const key = line.match(/^\s+"(\w+)" to listOf\($/);
    if (key) {
      current = pools[key[1]] = [];
      continue;
    }
    const entry = line.match(/^\s+"((?:[^"\\]|\\.)*)",$/);
    if (entry && current) {
      current.push(entry[1].replace(/\\(["\\$])/g, "$1"));
      continue;
    }
    if (/^\s{4}\)$/.test(line)) break; // end of mapOf(
  }
  if (Object.keys(pools).length === 0) throw new Error(`no pools parsed for ${name}`);
  return pools;
}

const out = {
  PL_CLEAN: parsePools("CleanJokes.kt", "CLEAN"),
  PL_SIGMA: parsePools("SigmaJokes.kt", "SIGMA"),
  EN_CLEAN: parsePools("EnJokes.kt", "CLEAN"),
  EN_SIGMA: parsePools("EnJokes.kt", "SIGMA"),
};

const body = Object.entries(out)
  .map(([name, pools]) => `const ${name}: Pools = ${JSON.stringify(pools, null, 2)};`)
  .join("\n\n");

writeFileSync(
  join(root, "src/lib/jokes.generated.ts"),
  `// GENERATED by scripts/gen-jokes.ts from the Kotlin pools in
// android/app/src/main/java/dev/pi0trdotsys/homebrewweather/widget/
// (CleanJokes.kt, SigmaJokes.kt, EnJokes.kt). Do not edit by hand.
import type { WeatherKind } from "./wmo";
import type { Lang } from "./i18n";
import type { Tone } from "./settings";
import { pickJoke } from "./line-picker";

type Pools = Record<string, string[]>;

${body}

/** Same pick rule as the widget (Jokes.pick, see line-picker.ts): the weather's own pool plus the
 * night, hot, cold and day-of-week lines that apply, and the next line of a fresh shuffle of
 * it each round — so no line comes back before the whole pool has been seen. */
export function pickFooterJoke(
  tone: Tone,
  lang: Lang,
  kind: WeatherKind,
  isNight: boolean,
  seed: number,
  temperature?: number | null,
  dow?: number | null,
): string {
  const pools =
    tone === "clean" ? (lang === "en" ? EN_CLEAN : PL_CLEAN) : lang === "en" ? EN_SIGMA : PL_SIGMA;
  return pickJoke(pools, kind, isNight, seed, temperature, dow);
}
`,
);
console.log(
  Object.entries(out)
    .map(([n, p]) => `${n}: ${Object.values(p).flat().length} lines`)
    .join(", "),
);

const wellbeing = {
  WELLBEING_PL: parsePools("WellbeingTips.kt", "PL"),
  WELLBEING_EN: parsePools("WellbeingTips.kt", "EN"),
};

for (const [name, pools] of Object.entries(wellbeing)) {
  if (!pools.calm?.length) throw new Error(`${name} has no "calm" pool (the fallback)`);
}

const wellbeingBody = Object.entries(wellbeing)
  .map(([name, pools]) => `export const ${name}: Pools = ${JSON.stringify(pools, null, 2)};`)
  .join("\n\n");

writeFileSync(
  join(root, "src/lib/wellbeing.generated.ts"),
  `// GENERATED by scripts/gen-jokes.ts from the Kotlin pools in
// android/app/src/main/java/dev/pi0trdotsys/homebrewweather/widget/WellbeingTips.kt.
// Do not edit by hand.
import type { Lang } from "./i18n";
import { lineIndex } from "./line-picker";

type Pools = Record<string, string[]>;

${wellbeingBody}

/** Same pick rule as the widget (WellbeingTips.pick, see line-picker.ts): the next line of a
 * fresh shuffle of the pool each round, the seed being the hour. An unknown situation falls
 * back to "calm". */
export function pickWellbeingTip(lang: Lang, situationKey: string, seed: number): string {
  const pools = lang === "en" ? WELLBEING_EN : WELLBEING_PL;
  const pool = pools[situationKey] ?? pools.calm;
  return pool[lineIndex(seed, pool.length)];
}
`,
);
console.log(
  Object.entries(wellbeing)
    .map(([n, p]) => `${n}: ${Object.values(p).flat().length} lines`)
    .join(", "),
);
